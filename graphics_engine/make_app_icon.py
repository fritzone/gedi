#!/usr/bin/env python3
"""Generate app_icon.h: the graphical build's window icon, embedded in the binary.

The window icon is what the taskbar, Alt+Tab and the window list show for
gedi-gui. It is compiled in rather than loaded from a file so it is there
however gedi was started - from the build directory, an AppImage or an
install - and without SDL_image.

Usage:  python3 graphics_engine/make_app_icon.py [icons/gt_gui.png] [size]

Writes graphics_engine/app_icon.h next to this script. Needs Pillow.
"""
import os
import sys

from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "icons", "gt_gui.png")
size = int(sys.argv[2]) if len(sys.argv) > 2 else 128

img = Image.open(src).convert("RGBA")
# Square it without distortion: centre the picture on a transparent canvas.
side = max(img.size)
canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
canvas.paste(img, ((side - img.width) // 2, (side - img.height) // 2))
icon = canvas.resize((size, size), Image.LANCZOS)

# Packed 0xAABBGGRR: SDL_PIXELFORMAT_ABGR8888, whatever the byte order.
raw = icon.tobytes()   # R, G, B, A per pixel
pixels = [(raw[i + 3] << 24) | (raw[i + 2] << 16) | (raw[i + 1] << 8) | raw[i]
          for i in range(0, len(raw), 4)]

out = os.path.join(here, "app_icon.h")
with open(out, "w") as f:
    f.write("// Generated by make_app_icon.py from icons/%s - do not edit.\n" % os.path.basename(src))
    f.write("// The graphical build's window icon (taskbar, Alt+Tab), %dx%d, packed\n" % (size, size))
    f.write("// 0xAABBGGRR pixels for SDL_PIXELFORMAT_ABGR8888.\n")
    f.write("#pragma once\n#include <cstdint>\n\n")
    f.write("constexpr int kAppIconSize = %d;\n" % size)
    f.write("static const std::uint32_t kAppIconPixels[%d] = {\n" % len(pixels))
    for i in range(0, len(pixels), 8):
        f.write("    " + ", ".join("0x%08x" % p for p in pixels[i:i + 8]) + ",\n")
    f.write("};\n")
print("wrote", out, "(%dx%d)" % (size, size))
